import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { mkdtemp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

const exec = promisify(execFile);
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const metadata = JSON.parse(await readFile(join(root, 'packages/cli/package.json'), 'utf8'));
const archive = join(root, 'artifacts', `memagent-${metadata.version}.tgz`);
const pnpm = process.env.npm_execpath;
assert(pnpm, 'Launch with pnpm test:package after pnpm pack:cli.');
const fixture = await mkdtemp(join(tmpdir(), 'memagent-install-'));
const consumer = join(fixture, 'consumer');
const project = join(fixture, 'project');
const home = join(fixture, 'home');
await Promise.all([consumer, project, home].map(path => mkdir(path)));
const env = { ...process.env, HOME: home, USERPROFILE: home, NODE_PATH: '',
  CODEX_HOME: join(home, '.codex'), CLAUDE_CONFIG_DIR: join(home, '.claude') };
const pmCommand = /\.[cm]?js$/i.test(pnpm) ? process.execPath : pnpm;
const pmArgs = /\.[cm]?js$/i.test(pnpm) ? [pnpm] : [];
const pm = (...args) => exec(pmCommand, [...pmArgs, ...args], { cwd: consumer, env, timeout: 120_000 });
console.log('Testing archive:', archive);
console.log('Isolated consumer:', consumer);
await writeFile(join(consumer, 'package.json'), JSON.stringify({ name: 'memagent-package-consumer', private: true }));
await pm('add', '--offline', '--ignore-scripts', archive);
const installed = join(consumer, 'node_modules', 'memagent');
const pkg = JSON.parse(await readFile(join(installed, 'package.json'), 'utf8'));
assert.equal(Object.keys(pkg.dependencies ?? {}).length, 0, 'Package must be self-contained');
assert.equal(pkg.bin.memagent, './dist/index.js');
assert.equal(pkg.license, 'MIT');
const rootLicense = await readFile(join(root, 'LICENSE'), 'utf8');
assert.equal(await readFile(join(installed, 'LICENSE'), 'utf8'), rootLicense);
assert((await readFile(join(installed, 'README.md'), 'utf8')).includes('MemAgent'));
assert((await readFile(join(installed, 'THIRD_PARTY_NOTICES.md'), 'utf8')).includes('TJ Holowaychuk'));
const version = await pm('exec', 'memagent', '--version');
assert.equal(version.stdout.trim(), metadata.version);
console.log('PASS: offline install, executable registration, version, MIT license and third-party notices.');
const cli = join(installed, 'dist/index.js');
const run = (...args) => exec(process.execPath, [cli, ...args], { cwd: project, env });
await writeFile(join(project, 'AGENTS.md'), '# Existing team instructions\n');
await writeFile(join(project, 'CLAUDE.md'), '# Existing Claude instructions\n');
await run('init', '--agent', 'both');
const result = await run('add', 'rule', 'Use pnpm in this project');
const id = /[a-f0-9]{12}/.exec(result.stdout)?.[0];
assert(id);
await run('add', 'decision', 'Keep the project memory in Markdown');
await run('add', 'note', 'Local pending task', '--private', '--ttl', 'never');
assert((await run('list')).stdout.includes('Use pnpm'));
assert((await run('list', '--private')).stdout.includes('Local pending task'));
const shared = await readFile(join(project, 'AGENTS.md'), 'utf8');
assert(shared.startsWith('# Existing team instructions\n'));
assert(!shared.includes('Local pending task'));
const personal = await readFile(join(project, 'AGENTS.override.md'), 'utf8');
assert(personal.includes('Existing team instructions'));
assert(personal.includes('Use pnpm') && personal.includes('Local pending task'));
const claude = await readFile(join(project, 'CLAUDE.md'), 'utf8');
assert(claude.startsWith('# Existing Claude instructions\n'));
assert(!claude.includes('Local pending task'));
await run('sync');
assert.equal(await readFile(join(project, 'AGENTS.md'), 'utf8'), shared);
await run('remove', id);
assert(!(await readFile(join(project, 'AGENTS.override.md'), 'utf8')).includes('Use pnpm'));
const child = await run('run', '--agent', 'codex', '--', process.execPath, '-e', 'console.log("installed-wrapper-ok")');
assert(child.stdout.includes('installed-wrapper-ok'));
console.log('PASS: installed CLI lifecycle, both exports, privacy, file preservation and wrapper.');
